"""The free bye-week planner's data: site/join/byes.json and the static table
on site/byes/index.html.

Usage:
    python -m render.bye_index --season 2026            # write both (make byes)
    python -m render.bye_index --season 2026 --check    # fail if either is stale

The planner (site/byes/) runs the weekly report's own bye rule in the browser
(engine.preseason.bye_collisions, mirrored by site/byes/byes.js and held equal
to it by tests/test_polish_tool.py). It needs three facts the player directory
does not carry, all of them FACTS, none a projection:

- **this season's byes**, team -> week, straight off the published schedule
  (engine.preseason.bye_by_team);
- **when each week ends** (run.solo.regular_week_end), so the page knows which
  week is being played by run.solo.current_week's own rule — the first week
  whose regular window has not closed — and starts its list there;
- **today's reserve list** (engine.availability.roster_out, ROSTER_OUT only):
  a player on injured reserve, the PUP or non-football injury list, suspended,
  exempt or released is not cover, exactly as WeekData.roster_out makes him not cover
  in the weekly report's "Byes ahead". Never LIVE_ONLY_OUT or PRACTICE_SQUAD:
  those are report-layer withholding rules, and run.solo._byes_ahead does not
  count them either, so adding them here would make the two surfaces tell one
  manager two different things about the same week.

It sits beside players.json and is regenerated by the same Tuesday step. A
wrong bye is worse than none — it sends somebody looking for a problem that is
not there — so it FAILS CLOSED: a schedule that gives fewer than 32 teams a
bye, a season with no weeks, or a season that is not players.json's season
refuses to write, and last week's dated file stays up. The reserve list is
dated on the page ("as of …") from ``reserve_as_of`` — when the players
release was last DOWNLOADED, read off the cached file itself — never from
``generated``: on an nflverse outage the cron falls back to the cached copy,
and a days-old list must not be labelled as today's (principle 3).

The season in the page's title, description and no-script line is rewritten
with the table (``with_season``), so a September rollover can never publish
next season's byes under last season's year.

RULE N1 rides in the asset (``attribution``) and in the table's source line.
"""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Mapping

from engine.availability import roster_out
from engine.preseason import bye_by_team
from ingest.nflverse import ATTRIBUTION, NflverseError, fetch

REPO_ROOT = Path(__file__).resolve().parent.parent
RAW_DIR = REPO_ROOT / "data" / "raw" / "nflverse"
DEFAULT_OUT = REPO_ROOT / "site" / "join" / "byes.json"
DEFAULT_PLAYERS = REPO_ROOT / "site" / "join" / "players.json"
DEFAULT_PAGE = REPO_ROOT / "site" / "byes" / "index.html"

START = "<!-- byes:start -->"
END = "<!-- byes:end -->"
TEAMS = 32
SOURCE_LINE = "Schedule: nflverse (nflverse-data), CC-BY-4.0."


class ByeIndexError(RuntimeError):
    """The inputs cannot honestly make a planner file; nothing is written."""


def _display(path: Path) -> str:
    try:
        return str(path.relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def build(season: str, raw_dir: Path, directory_payload: Mapping[str, Any],
          generated_at: str | None = None) -> dict[str, Any]:
    """The whole payload from the CACHED schedule and players release.

    ``directory_payload`` is site/join/players.json: the reserve list is cut
    to the ids the planner can resolve, which keeps the file small and keeps
    it to players a visitor can actually put on a roster."""
    from run.solo import _schedule, _weeks, regular_week_end

    season = str(season)
    weeks = _weeks(_schedule(Path(raw_dir), live=False), season)
    if not weeks:
        raise ByeIndexError(f"the schedule carries no {season} regular season")
    by_team = bye_by_team(Path(raw_dir), season)
    idle: dict[int, list[str]] = {}
    for team, week in by_team.items():
        idle.setdefault(int(week), []).append(str(team))
    ids = {row[1] for row in directory_payload.get("players") or []}
    players_csv = Path(raw_dir) / "players.csv"
    out = roster_out(players_csv)
    return {
        "season": season,
        "generated": generated_at or datetime.now(timezone.utc)
                     .replace(microsecond=0).isoformat(),
        # When the reserve list was fetched: the cached file's own write time,
        # which an outage's fallback leaves at its real (older) date.
        "reserve_as_of": datetime.fromtimestamp(players_csv.stat().st_mtime, timezone.utc)
                         .replace(microsecond=0).isoformat(),
        # RULE N1: the licence term travels with the data it licenses.
        "attribution": ATTRIBUTION,
        "last_week": max(weeks),
        "weeks": [{"week": week, "ends": regular_week_end(weeks[week]),
                   "bye": sorted(idle.get(week, []))}
                  for week in sorted(weeks)],
        "out": {gsis: reason for gsis, reason in sorted(out.items()) if gsis in ids},
    }


def validate(payload: Mapping[str, Any], directory_payload: Mapping[str, Any]) -> None:
    """Raise ByeIndexError for a payload that would publish a wrong bye."""
    season = str(payload.get("season"))
    if not payload.get("weeks"):
        raise ByeIndexError(f"no {season} weeks in the schedule")
    teams = {team for week in payload["weeks"] for team in week["bye"]}
    if len(teams) < TEAMS:
        raise ByeIndexError(f"only {len(teams)} teams have a {season} bye, not {TEAMS} — "
                            f"refusing to publish a partial bye list")
    theirs = str(directory_payload.get("season"))
    if theirs != season:
        raise ByeIndexError(f"players.json is the {theirs} directory and this is the "
                            f"{season} schedule — the planner would join two seasons")


def dumps(payload: Mapping[str, Any]) -> str:
    """Keys sorted, compact, UTF-8 as written: byte-identical for the same inputs."""
    return json.dumps(payload, separators=(",", ":"), sort_keys=True,
                      ensure_ascii=False) + "\n"


def _ranges(weeks: list[int]) -> str:
    """[1, 2, 3, 4, 12, 15, 16, 17, 18] -> "1–4, 12 and 15–18"."""
    runs: list[list[int]] = []
    for week in sorted(weeks):
        if runs and week == runs[-1][-1] + 1:
            runs[-1].append(week)
        else:
            runs.append([week])
    parts = [f"{run[0]}–{run[-1]}" if len(run) > 1 else str(run[0]) for run in runs]
    return parts[0] if len(parts) == 1 else ", ".join(parts[:-1]) + " and " + parts[-1]


def table_html(payload: Mapping[str, Any], players_payload: Mapping[str, Any]) -> str:
    """The static table between the page's byes:start and byes:end markers:
    every week that has byes, by team name, then the weeks with none. The
    page renders it with or without JavaScript, so a visitor (and a crawler)
    sees the season's byes whatever the planner itself can do."""
    names = {row[3]: row[0] for row in players_payload.get("players") or []
             if row[2] == "DEF" and row[3]}
    esc = html.escape
    lines = [f'<h2 id="every-bye">Every {esc(str(payload["season"]))} NFL bye week</h2>',
             '<ul class="byetable">']
    empty: list[int] = []
    for week in payload["weeks"]:
        if not week["bye"]:
            empty.append(int(week["week"]))
            continue
        teams = sorted(names.get(team, team) for team in week["bye"])
        lines.append(f"<li><b>Week {int(week['week'])}</b> — "
                     f"{esc(', '.join(teams))}</li>")
    lines.append("</ul>")
    if empty:
        noun = "Week" if len(empty) == 1 else "Weeks"
        lines.append(f"<p>No byes in {noun} {esc(_ranges(empty))}.</p>")
    lines.append(f'<p class="src">{esc(SOURCE_LINE)}</p>')
    return "\n".join(lines)


def with_table(page: str, block: str) -> str:
    """``page`` with its marked block replaced by ``block``."""
    if page.count(START) != 1 or page.count(END) != 1 or page.index(START) > page.index(END):
        raise ByeIndexError(f"the planner page needs exactly one {START} … {END} block")
    head, rest = page.split(START, 1)
    _old, tail = rest.split(END, 1)
    return f"{head}{START}\n{block}\n{END}{tail}"


# The page's other mentions of the season, outside the marked table. Each must
# appear exactly once: a page that no longer carries one is a template change
# this generator has not been taught, and it refuses rather than guessing.
_SEASON_SPOTS = (
    re.compile(r"(<title>Fantasy football bye week planner \()\d{4}(\))"),
    re.compile(r"(Every )\d{4}( bye, by week\.)"),
    re.compile(r"(Every )\d{4}( bye week is listed below\.)"),
)


def with_season(page: str, season: str) -> str:
    """``page`` with its title, description and no-script line naming ``season``."""
    for pattern in _SEASON_SPOTS:
        if len(pattern.findall(page)) != 1:
            raise ByeIndexError(f"the planner page needs exactly one {pattern.pattern!r}")
        page = pattern.sub(lambda m: f"{m.group(1)}{int(season)}{m.group(2)}", page)
    return page


def table_in(page: str) -> str:
    """The block currently between the markers."""
    return page.split(START, 1)[1].split(END, 1)[0].strip("\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--season", required=True)
    parser.add_argument("--raw", type=Path, default=RAW_DIR)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--players", type=Path, default=DEFAULT_PLAYERS)
    parser.add_argument("--page", type=Path, default=DEFAULT_PAGE)
    parser.add_argument("--check", action="store_true",
                        help="fail if the committed file or page table is stale, without writing")
    parser.add_argument("--offline", action="store_true",
                        help="read the cached schedule and players release as they are "
                             "(the suite's mode; the cron revalidates)")
    args = parser.parse_args(argv)

    if not args.offline:
        # live=True, like render/player_index: the reserve list changes daily
        # and the schedule moves a game now and then. An outage falls back to
        # the cached copy; only a cold cache is fatal.
        try:
            fetch("schedules", "games.csv", args.raw, live=True)
            fetch("players", "players.csv", args.raw, live=True)
        except NflverseError as exc:
            print(f"could not fetch the bye planner's inputs: {exc}", file=sys.stderr)
            return 1
    try:
        directory = json.loads(args.players.read_text(encoding="utf-8"))
        payload = build(args.season, args.raw, directory)
        validate(payload, directory)
        page = args.page.read_text(encoding="utf-8")
        new_page = with_season(with_table(page, table_html(payload, directory)),
                               payload["season"])
    except (ByeIndexError, NflverseError, OSError, ValueError, KeyError) as exc:
        print(f"refusing to write the bye planner's data: {exc} — last week's file stays",
              file=sys.stderr)
        return 1

    if args.check:
        stale = []
        try:
            current = json.loads(args.output.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            current = None
        # Both stamps move with every fetch, never with the facts.
        drop = lambda d: {k: v for k, v in (d or {}).items()  # noqa: E731
                          if k not in ("generated", "reserve_as_of")}
        if current is None or drop(current) != drop(payload):
            stale.append(_display(args.output))
        if new_page != page:
            stale.append(_display(args.page))
        if stale:
            print(f"{' and '.join(stale)} stale — run `make byes`", file=sys.stderr)
            return 1
        print(f"{args.output.name} and the planner's table are up to date")
        return 0

    body = dumps(payload)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(body, encoding="utf-8")
    if new_page != page:
        args.page.write_text(new_page, encoding="utf-8")
    import gzip
    teams = sum(len(week["bye"]) for week in payload["weeks"])
    print("=" * 62)
    print(f"bye planner data -> {_display(args.output)}")
    print(f"  season          : {payload['season']} (weeks 1-{payload['last_week']}, "
          f"{teams} team byes)")
    print(f"  reserve list    : {len(payload['out'])} players")
    print(f"  size            : {len(body.encode()):,} bytes raw, "
          f"{len(gzip.compress(body.encode())):,} gzipped")
    print(f"  page table      : {_display(args.page)}")
    print(f"  {ATTRIBUTION}")
    print("=" * 62)
    return 0


if __name__ == "__main__":
    sys.exit(main())
