"""Hash-locked installs: requirements.lock and requirements-dev.lock, from
requirements.txt (INFRA-07, pre-launch review Oct 2026).

Usage (a deliberate local act, like `make og` — it needs PyPI):
    make lock            # .venv/bin/python -m infra.lock_requirements

Why. requirements.txt pinned three packages and nothing else: urllib3, idna,
certifi and charset-normalizer floated (certifi resolved to a release made the
same morning the review ran), no file was checked against a hash, and every
cron installed pytest and PyYAML beside STRIPE_API_KEY, RESEND_API_KEY and
LOG_SECRET — a wheel only needs a .pth file to run on every interpreter
start. Now:

- **requirements.lock** — the runtime set (requests and what it pulls in),
  every file's sha256. Every cron installs ONLY this, with --require-hashes,
  so a package that is not listed, or a file whose hash is not listed, stops
  the install.
- **requirements-dev.lock** — the runtime set plus the test tools, for CI.
- **A 14-day cooldown**: the resolver only considers releases uploaded at
  least 14 days ago (pip's --uploaded-prior-to), because a malicious release
  is usually caught and pulled within days. A pin in requirements.txt younger
  than that refuses, loudly.
- Hashes cover EVERY published file of each version (wheels for every
  platform, and the sdist), so the same lock installs on the Linux runners and
  on a Mac. Resolution is for CPython 3.11, what every workflow uses.

requirements.txt stays the human-edited source (and what Dependabot bumps).
tests/test_prelaunch_infra.py fails when a lock no longer matches it, so a
Dependabot bump goes red until somebody runs `make lock` and commits both.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SOURCE = REPO_ROOT / "requirements.txt"
RUNTIME_LOCK = REPO_ROOT / "requirements.lock"
DEV_LOCK = REPO_ROOT / "requirements-dev.lock"
DEV_MARKER = "# Development"
COOLDOWN = "P14D"
PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;#]+)\s*$")
HEADER = ("# GENERATED by `make lock` (infra/lock_requirements.py) from requirements.txt.\n"
          "# Do not edit by hand. Install with: pip install --require-hashes -r {name}\n"
          "# {what}\n")


def normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_source(text: str) -> tuple[dict[str, str], dict[str, str]]:
    """(runtime pins, dev pins) from requirements.txt: everything before the
    "# Development" line is runtime. Every requirement must be an exact pin."""
    runtime: dict[str, str] = {}
    dev: dict[str, str] = {}
    section = runtime
    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith(DEV_MARKER):
            section = dev
            continue
        if not line or line.startswith("#"):
            continue
        match = PIN.match(line)
        if not match:
            raise ValueError(f"requirements.txt: {line!r} is not an exact pin (name==version)")
        section[normalise(match.group(1))] = match.group(2)
    if not runtime:
        raise ValueError("requirements.txt has no runtime pins above the "
                         f"{DEV_MARKER!r} line")
    return runtime, dev


def parse_lock(text: str) -> dict[str, tuple[str, list[str]]]:
    """{name: (version, [sha256, ...])} from a lock file."""
    entries: dict[str, tuple[str, list[str]]] = {}
    current = None
    for raw in text.splitlines():
        line = raw.strip().rstrip("\\").strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("--hash=sha256:"):
            if current is None:
                raise ValueError("a hash before any requirement")
            entries[current][1].append(line.split(":", 1)[1])
            continue
        match = re.match(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==(\S+)$", line)
        if not match:
            raise ValueError(f"unexpected lock line {raw!r}")
        current = normalise(match.group(1))
        entries[current] = (match.group(2), [])
    return entries


def resolve(pins: dict[str, str]) -> dict[str, str]:
    """{name: version} pip would install for ``pins``, on this interpreter."""
    with tempfile.TemporaryDirectory() as tmp:
        reqs = Path(tmp) / "in.txt"
        report = Path(tmp) / "report.json"
        reqs.write_text("".join(f"{n}=={v}\n" for n, v in pins.items()), encoding="utf-8")
        done = subprocess.run(
            [sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed",
             "--quiet", "--disable-pip-version-check", "--uploaded-prior-to", COOLDOWN,
             "--report", str(report), "-r", str(reqs)],
            capture_output=True, text=True, check=False)
        if done.returncode != 0:
            raise SystemExit("pip could not resolve requirements.txt with a "
                             f"{COOLDOWN} cooldown — a pin may be younger than that:\n"
                             + done.stderr[-1500:])
        data = json.loads(report.read_text(encoding="utf-8"))
    return {normalise(item["metadata"]["name"]): item["metadata"]["version"]
            for item in data["install"]}


def hashes(name: str, version: str) -> list[str]:
    """sha256 of every file PyPI publishes for ``name==version``."""
    import requests
    response = requests.get(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30)
    response.raise_for_status()
    files = response.json().get("urls") or []
    digests = sorted({f["digests"]["sha256"] for f in files if f.get("digests", {}).get("sha256")})
    if not digests:
        raise SystemExit(f"PyPI lists no files for {name}=={version}")
    return digests


def render(resolved: dict[str, str], name: str, what: str) -> str:
    lines = [HEADER.format(name=name, what=what)]
    for package in sorted(resolved):
        version = resolved[package]
        digests = hashes(package, version)
        lines.append(f"{package}=={version} \\\n"
                     + " \\\n".join(f"    --hash=sha256:{d}" for d in digests) + "\n")
    return "".join(lines)


def main(argv: list[str] | None = None) -> int:
    runtime, dev = parse_source(SOURCE.read_text(encoding="utf-8"))
    for pins, path, what in (
            (runtime, RUNTIME_LOCK, "Runtime only — what every cron installs beside the live secrets."),
            ({**runtime, **dev}, DEV_LOCK, "Runtime plus the test tools — what CI's test job installs.")):
        resolved = resolve(pins)
        for package, version in pins.items():
            if resolved.get(package) != version:
                raise SystemExit(f"{package}: requirements.txt pins {version}, pip resolved "
                                 f"{resolved.get(package)}")
        path.write_text(render(resolved, path.name, what), encoding="utf-8")
        print(f"{path.name}: {len(resolved)} packages, "
              + ", ".join(f"{p}=={v}" for p, v in sorted(resolved.items())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
